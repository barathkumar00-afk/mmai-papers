"""Multimodal fusion and orchestration service.

.. warning::

   **This is an integration / prototype fusion layer, not a trained neural fusion
   model.** There is no cross-attention encoder, no latent alignment network, and
   no learned joint embedding space in this repository. :class:`MultimodalFusionService`
   combines *structured representations* produced by the per-modality services
   into a unified patient record, then hands that record to retrieval and to the
   configured local LLM. The ``model`` block of every response states this
   explicitly via ``is_trained_neural_fusion_model = False``.

Pipeline::

    image  -> VisionService      ---\\
    audio  -> SpeechService      ----> MultimodalFusionService
    text   -> ClinicalService    ---/            |
                                                   v
                                 unified patient representation
                                                   |
                                       retrieval query generation
                                                   |
                                         FAISS retrieval -> evidence
                                                   |
                                          RAG grounded reasoning
                                                   |
                                    candidate interpretations + uncertainty
"""

