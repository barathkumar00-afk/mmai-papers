class StageTimer:
    """Measures real wall-clock duration for each pipeline stage."""

    def __init__(self) -> None:
        self.stages: List[StageTiming] = []
        self._started = time.perf_counter()

    def record(self, stage: str, started: float, *, simulated: bool = False) -> None:
        self.stages.append(
            StageTiming(
                stage=stage,
                duration_ms=round((time.perf_counter() - started) * 1000, 2),
                simulated=simulated,
            )
        )

    @property
    def total_ms(self) -> float:
        return round((time.perf_counter() - self._started) * 1000, 2)


class MultimodalFusionService:
    """Integration-layer fusion over per-modality structured representations."""

    #: Label used for heuristic, non-attribution contribution shares.
    ATTRIBUTION_METHOD = "heuristic_evidence_coverage"

    def _limitations(self) -> List[Limitations]:
        return [
            Limitations(
                statement=(
                    "The fusion layer is an integration/prototype component that combines "
                    "structured per-modality representations. It is NOT a trained cross-attention "
                    "or latent-alignment neural network, and its contribution weights are "
                    "heuristic evidence-coverage shares, not learned attention."
                ),
                category="model_transparency",
            ),
            Limitations(
                statement=(
                    "Modality contribution values are derived from how much observed evidence a "
                    "modality supplied. They are not attention weights, gradients, or any other "
                    "measured model attribution."
                ),
                category="explainability_scope",
            ),
            Limitations(
                statement=(
                    "Candidate interpretations are decision-support hypotheses generated by a "
                    "language model. They are not diagnoses, are not calibrated probabilities, "
                    "and require independent clinical verification."
                ),
                category="clinical_safety",
            ),
            Limitations(
                statement=(
                    "This prototype has not been clinically validated. No accuracy, sensitivity, "
                    "specificity, F1 or AUC figure is claimed for it."
                ),
                category="validation_status",
            ),
        ]

    # ------------------------------------------------------ observed evidence
    @staticmethod
    def _observed_from_image(image: Optional[ImageAnalysisResponse]) -> List[ObservedEvidence]:
        items: List[ObservedEvidence] = []
        if not image:
            return items
        for index, observation in enumerate(image.observations, start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"image-e{index}",
                    modality="image",
                    statement=observation.finding,
                    source=observation.source,
                    confidence=observation.confidence,
                    detail=observation.uncertainty_note,
                )
            )
        for index, feature in enumerate(image.visual_features[:8], start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"image-f{index}",
                    modality="image",
                    statement=(
                        f"Measured visual feature '{feature.name}' = {feature.value} "
                        f"({feature.category})."
                    ),
                    source="measured",
                    confidence=1.0,
                    detail=feature.notes,
                )
            )
        return items

    @staticmethod
    def _observed_from_speech(speech: Optional[SpeechAnalysisResponse]) -> List[ObservedEvidence]:
        items: List[ObservedEvidence] = []
        if not speech:
            return items
        for index, observation in enumerate(speech.clinical_observations, start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"speech-e{index}",
                    modality="speech",
                    statement=observation.observation,
                    source=observation.source,
                    confidence=observation.confidence,
                    detail=observation.uncertainty_note,
                )
            )
        for index, feature in enumerate(speech.speech_features[:6], start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"speech-f{index}",
                    modality="speech",
                    statement=f"Measured acoustic feature '{feature.name}' = {feature.value}{feature.unit}.",
                    source="measured",
                    confidence=1.0,
                    detail=feature.notes,
                )
            )
        return items

    @staticmethod
    def _observed_from_clinical(
        clinical: Optional[ClinicalAnalysisResponse]
    ) -> List[ObservedEvidence]:
        items: List[ObservedEvidence] = []
        if not clinical:
            return items
        for index, feature in enumerate(clinical.clinical_features[:14], start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"clinical-e{index}",
                    modality="clinical",
                    statement=f"{feature.name}: {feature.detail}",
                    source="rule_based",
                    confidence=feature.confidence,
                    detail=f"Rule: {feature.rule}",
                )
            )
        for index, (name, value) in enumerate(list(clinical.vitals.items())[:6], start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"clinical-v{index}",
                    modality="clinical",
                    statement=f"Vital sign {name} = {(value or {}).get('raw', '')}".strip(),
                    source="reported",
                    confidence=None,
                    detail=f"Direction: {(value or {}).get('direction') or 'unknown'}",
                )
            )
        for index, (name, value) in enumerate(list(clinical.labs.items())[:6], start=1):
            items.append(
                ObservedEvidence(
                    evidence_id=f"clinical-l{index}",
                    modality="clinical",
                    statement=f"Lab {name} = {(value or {}).get('raw', '')}".strip(),
                    source="reported",
                    confidence=None,
                    detail=f"Direction: {(value or {}).get('direction') or 'unknown'}",
                )
            )
        return items

    # ------------------------------------------------------- unified record
    def _unified_representation(
        self,
        *,
        image: Optional[ImageAnalysisResponse],
        speech: Optional[SpeechAnalysisResponse],
        clinical: Optional[ClinicalAnalysisResponse],
    ) -> Dict[str, Any]:
        """Structural (not learned) merge of the three modality representations."""
        record: Dict[str, Any] = {
            "schema": "medexplain.unified_patient.v1",
            "produced_by": "MultimodalFusionService (integration layer)",
            "is_trained_neural_fusion_model": False,
            "modalities": {},
        }
        if image:
            record["modalities"]["image"] = {
                "modality": image.modality,
                "observation_count": len(image.observations),
                "feature_count": len(image.visual_features),
                "format": image.metadata.format,
                "dimensions": f"{image.metadata.width}x{image.metadata.height}",
                "is_dicom": image.metadata.is_dicom,
                "provenance": image.provenance.mode,
            }
        if speech:
            record["modalities"]["speech"] = {
                "observation_count": len(speech.clinical_observations),
                "feature_count": len(speech.speech_features),
                "transcript_available": bool(speech.transcript),
                "duration_seconds": speech.metadata.duration_seconds,
                "provenance": speech.provenance.mode,
            }
        if clinical:
            record["modalities"]["clinical"] = {
                "symptom_count": len(clinical.symptoms),
                "lab_count": len(clinical.labs),
                "vital_count": len(clinical.vitals),
                "feature_count": len(clinical.clinical_features),
                "provenance": clinical.provenance.mode,
            }
        record["modalities_present"] = sorted(record["modalities"].keys())
        record["modalities_missing"] = [
            name for name in ("image", "speech", "clinical") if name not in record["modalities"]
        ]
        return record

    # ------------------------------------------------- heuristic contribution
    def _contributions(
        self,
        observed_by_modality: Dict[str, List[ObservedEvidence]],
        candidates: Sequence[CandidateInterpretation],
    ) -> List[ModalityContribution]:
        """Evidence-coverage shares. Explicitly *not* attention weights."""
        referenced = set()
        for candidate in candidates:
            for entry in candidate.supporting_evidence + candidate.contradicting_evidence:
                referenced.add(entry.split(":", 1)[0].strip())

        contributions: List[ModalityContribution] = []
        for modality in ("image", "speech", "clinical"):
            items = observed_by_modality.get(modality, [])
            statements = [item.statement for item in items[:6]]
            cited = sum(1 for item in items if item.evidence_id in referenced)
            share = cited if cited else 0
            contributions.append(
                ModalityContribution(
                    modality=modality,
                    observations=statements,
                    evidence_count=len(items),
                    relative_support=None,  # normalized below once totals are known
                    method=self.ATTRIBUTION_METHOD,
                    is_measured_attribution=False,
                )
            )

        cited_totals = [c.evidence_count for c in contributions]
        raw = [
            sum(
                1
                for item in observed_by_modality.get(c.modality, [])
                if item.evidence_id in referenced
            )
            for c in contributions
        ]
        if any(raw):
            total = float(sum(raw))
            for contribution, value in zip(contributions, raw):
                contribution.relative_support = round(value / total, 4)
        else:
            evidence_total = sum(cited_totals)
            for contribution in contributions:
                contribution.relative_support = (
                    round(contribution.evidence_count / evidence_total, 4)
                    if evidence_total
                    else 0.0
                )
        return contributions

    # --------------------------------------------------------------- scoring
    @staticmethod
    def _assign_weights(
        candidates: List[CandidateInterpretation],
        *,
        simulated: bool,
    ) -> None:
        """Fill candidate weights from *relative* support, never as probabilities.

        A weight is the share of verifiable supporting evidence references this
        candidate carries, relative to the strongest candidate. It is explicitly
        not a calibrated probability, and it is withheld entirely when no
        candidate cites any verifiable evidence.
        """
        if not candidates:
            return
        scores: List[float] = []
        for candidate in candidates:
            supporting = len(candidate.supporting_evidence)
            contradicting = len(candidate.contradicting_evidence)
            scores.append(max(supporting - contradicting, 0) + (0.25 * supporting))
        top = max(scores) if scores else 0.0
        if top <= 0:
            return
        for candidate, score in zip(candidates, scores):
            candidate.weight = round(clamp(score / top), 4)
            candidate.probability_is_calibrated = False

    @staticmethod
    def _evidence_support_confidence(
        *,
        observed: Sequence[ObservedEvidence],
        candidates: Sequence[CandidateInterpretation],
        retrieved_count: int,
        modalities_present: int,
        hedging: float,
    ) -> Tuple[float, str, List[str]]:
        """Derive a confidence figure from observable inputs, with its basis stated.

        This is a transparent, reproducible heuristic -- explicitly *not* a
        calibrated diagnostic accuracy. When no local LLM was used, the figure is
        reported as ``simulated``.
        """
        drivers: List[str] = []
        evidence_count = len(observed)
        if evidence_count == 0:
            return 0.0, "no evidence available", ["No observed evidence was available."]
        if candidates:
            coverage = rag_service.evidence_coverage(candidates, evidence_count)
        else:
            coverage = 0.0

        score = 0.25
        score += 0.25 * clamp(min(evidence_count / 12.0, 1.0))
        score += 0.20 * coverage
        score += 0.10 * clamp(modalities_present / 3.0)
        score += 0.10 * clamp(retrieved_count / 3.0)
        score += 0.10 * (1.0 - clamp(hedging))

        basis = (
            f"heuristic evidence-coverage score: {evidence_count} observed evidence item(s), "
            f"{len(candidates)} candidate(s), coverage={coverage:.2f}, "
            f"{modalities_present}/3 modalities present, {retrieved_count} retrieved document(s), "
            f"hedging={hedging:.2f}. NOT a calibrated diagnostic probability."
        )
        if coverage < 0.2:
            drivers.append("Candidates cite little verifiable evidence, so confidence is low.")
        if modalities_present < 3:
            drivers.append(f"Only {modalities_present} of 3 modalities contributed evidence.")
        if retrieved_count == 0:
            drivers.append("No retrieved evidence was available to ground the reasoning.")
        if hedging > 0.5:
            drivers.append("The reasoning component hedged heavily, indicating low assurance.")
        return round(clamp(score), 4), basis, drivers

    # ------------------------------------------------------------------ main
    async def analyze(
        self,
        *,
        image_data: Optional[bytes] = None,
        image_filename: str = "upload",
        image_modality_hint: Optional[str] = None,
        image_focus: Optional[str] = None,
        window_level: Optional[List[float]] = None,
        de_identify: bool = True,
        audio_data: Optional[bytes] = None,
        audio_filename: str = "clip.wav",
        audio_language: Optional[str] = None,
        clinical: Optional[ClinicalInput] = None,
        case_id: str = "#MED-2025-0941",
        top_k: int = 5,
        weights: Optional[Dict[str, float]] = None,
        request_id: Optional[str] = None,
    ) -> MultimodalAnalysisResponse:
        timer = StageTimer()
        rid = request_id or uuid.uuid4().hex[:12]
        settings = get_settings()
        warnings: List[str] = []

        if image_data is None and audio_data is None and clinical is None:
            from app.core.errors import AppError, ErrorCode

            raise AppError(
                ErrorCode.MISSING_PARAMETER,
                "At least one of image, audio, or clinical data must be provided.",
                status_code=400,
            )

        clinical_input = clinical or ClinicalInput()
        if clinical_input.all_text().strip() or clinical_input.labs or clinical_input.vitals:
            pass

        # ------------------------------------------------ stage 1: modalities
        image_result: Optional[ImageAnalysisResponse] = None
        if image_data:
            started = time.perf_counter()
            try:
                image_result = await vision_service.analyze(
                    image_data,
                    filename=image_filename,
                    modality_hint=image_modality_hint,
                    window_level=window_level,
                    de_identify=de_identify,
                    focus=image_focus,
                    request_id=rid,
                )
            except Exception as exc:
                logger.warning("multimodal_image_failed", extra={"error": str(exc)[:300]})
                warnings.append(f"Image analysis failed: {str(exc)[:200]}")
            timer.record("vision_extract", started, simulated=bool(image_result and image_result.provenance.simulated))

        speech_result: Optional[SpeechAnalysisResponse] = None
        if audio_data:
            started = time.perf_counter()
            try:
                speech_result = await speech_service.analyze(
                    audio_data, filename=audio_filename, language=audio_language, request_id=rid
                )
            except Exception as exc:
                logger.warning("multimodal_speech_failed", extra={"error": str(exc)[:300]})
                warnings.append(f"Speech analysis failed: {str(exc)[:200]}")
            timer.record("speech_tokenize", started, simulated=bool(speech_result and speech_result.provenance.simulated))

        clinical_result: Optional[ClinicalAnalysisResponse] = None
        started = time.perf_counter()
        try:
            clinical_result = await clinical_service.analyze(clinical_input, request_id=rid)
        except Exception as exc:
            logger.warning("multimodal_clinical_failed", extra={"error": str(exc)[:300]})
            warnings.append(f"Clinical normalization failed: {str(exc)[:200]}")
        timer.record("clinical_ingest", started)

        # ------------------------------------------------- stage 2: alignment
        started = time.perf_counter()
        observed_by_modality: Dict[str, List[ObservedEvidence]] = {
            "image": self._observed_from_image(image_result),
            "speech": self._observed_from_speech(speech_result),
            "clinical": self._observed_from_clinical(clinical_result),
        }
        observed: List[ObservedEvidence] = [
            item for modality in ("image", "speech", "clinical") for item in observed_by_modality[modality]
        ]
        unified = self._unified_representation(
            image=image_result, speech=speech_result, clinical=clinical_result
        )
        timer.record("multimodal_alignment", started, simulated=True)

        # ------------------------------------------- stage 3: query + retrieve
        query_parts: List[str] = []
        if clinical_result and clinical_result.retrieval_query:
            query_parts.append(clinical_result.retrieval_query)
        if speech_result and speech_result.transcript:
            query_parts.append(truncate(speech_result.transcript, 600))
        if image_result:
            for observation in image_result.observations[:4]:
                if observation.source in {"model_reported", "measured"}:
                    query_parts.append(truncate(observation.finding, 200))
        retrieval_query = " | ".join(p for p in query_parts if p) or "acute clinical presentation"

        started = time.perf_counter()
        search = await retrieval_service.search(retrieval_query, top_k=top_k)
        retrieved = search.get("evidence", []) or []
        timer.record("faiss_retrieval", started, simulated=not search.get("knowledge_base_initialized"))
        if not search.get("knowledge_base_initialized"):
            message = search.get("message") or "Knowledge base not initialized"
            warnings.append(f"Retrieval unavailable: {message}")
            logger.info("retrieval_unavailable", extra={"detail": message})

        # ------------------------------------------ stage 4: grounded reasoning
        uncertainty_drivers: List[str] = []
        missing_information: List[str] = []
        for name, result in (
            ("image", image_result),
            ("speech", speech_result),
            ("clinical", clinical_result),
        ):
            if result is None:
                uncertainty_drivers.append(f"No {name} modality was provided.")
                continue
            uncertainty_drivers.extend(result.uncertainty.drivers)
            missing_information.extend(result.missing_information)
        uncertainty_drivers = dedupe_preserve_order(uncertainty_drivers)[:12]
        missing_information = dedupe_preserve_order(missing_information)[:12]

        started = time.perf_counter()
        reasoning = await rag_service.reason(
            observed=observed,
            retrieved=retrieved,
            uncertainty_drivers=uncertainty_drivers,
            missing_information=missing_information,
            query=retrieval_query,
            top_k=top_k,
            weights=weights,
        )
        timer.record("rag_reasoning", started, simulated=not reasoning.get("available"))

        candidates: List[CandidateInterpretation] = reasoning.get("candidates", []) or []
        simulated_reasoning = not reasoning.get("available")
        self._assign_weights(candidates, simulated=simulated_reasoning)

        # --------------------------------------------------- stage 5: synthesis
        started = time.perf_counter()
        modalities_present = len([m for m, items in observed_by_modality.items() if items])
        hedging = rag_service.hedging_score(reasoning.get("summary") or "")
        confidence, confidence_basis, confidence_drivers = self._evidence_support_confidence(
            observed=observed,
            candidates=candidates,
            retrieved_count=len(retrieved),
            modalities_present=modalities_present,
            hedging=hedging,
        )
        if simulated_reasoning:
            confidence_basis = (
                "simulated: no local LLM was called, so this figure reflects observed evidence "
                "coverage only. " + confidence_basis
            )
        contributions = self._contributions(observed_by_modality, candidates)
        timer.record("synthesis", started, simulated=simulated_reasoning)

        primary_finding, rationale = self._synthesize(
            summary=reasoning.get("summary") or "",
            candidates=candidates,
            observed=observed,
            simulated=simulated_reasoning,
        )
        recommendations = self._recommendations(
            candidates=candidates, clinical=clinical_result, observed=observed
        )

        # ------------------------------------------------------------- meta
        if reasoning.get("error"):
            warnings.append(f"Reasoning unavailable: {reasoning['error']}")
        if reasoning.get("overclaim_detected"):
            warnings.append(
                "The reasoning component produced an overconfident statement; it was flagged "
                "and hedged before inclusion."
            )
        if not candidates:
            warnings.append(
                "No candidate interpretations were produced. This indicates insufficient "
                "grounded evidence, not a negative clinical result."
            )

        drivers = dedupe_preserve_order(confidence_drivers + uncertainty_drivers)[:12]
        overall_uncertainty = round(clamp(1.0 - confidence), 4)
        uncertainty_block = Uncertainty(
            overall=overall_uncertainty,
            confidence=confidence,
            epistemic=round(clamp(overall_uncertainty * 0.6), 4),
            aleatoric=round(clamp(overall_uncertainty * 0.4), 4),
            drivers=drivers,
            missing_information=missing_information,
            notes=confidence_basis,
        )

        fully_simulated = all(
            result is None or result.provenance.simulated
            for result in (image_result, speech_result, clinical_result)
        )
        provenance = Provenance(
            mode="simulated" if fully_simulated else "real",
            label="DEMO / SIMULATED" if fully_simulated else "MIXED REAL / PARTIAL",
            computed_by="MultimodalFusionService (integration layer)",
            simulated=fully_simulated,
            notes=(
                "Measured features and deterministic normalization are real computations. "
                + (
                    "No local models were called (MOCK_MODE or none configured), so no "
                    "model-generated clinical content is present."
                    if fully_simulated
                    else "At least one local model contributed. Interpretations remain model "
                    "generations requiring clinician verification."
                )
            ),
        )

        models: Dict[str, ModelInfo] = {
            "fusion": model_manager.fusion_info(),
            "reasoning": model_manager.llm_info(
                "ready" if reasoning.get("available") else ("simulated" if settings.MOCK_MODE else "unavailable")
            ),
            "retrieval": retrieval_service and model_manager.embedding_info(
                "ready" if search.get("knowledge_base_initialized") else "uninitialized"
            ),
        }
        if image_result:
            models["vision"] = image_result.model
        if speech_result:
            models["speech"] = speech_result.model

        return MultimodalAnalysisResponse(
            success=True,
            case_id=case_id,
            primary_finding=primary_finding,
            rationale=rationale,
            differential_ranking=candidates,
            recommendations=recommendations,
            confidence=confidence,
            uncertainty=overall_uncertainty,
            confidence_basis=confidence_basis,
            confidence_is_calibrated=False,
            observed_evidence=observed,
            retrieved_evidence=[item.model_dump() for item in retrieved],
            model_generated_interpretations=[c.label for c in candidates],
            missing_information=missing_information,
            evidence_trace=reasoning.get("reasoning_steps", []) or [],
            image=image_result,
            speech=speech_result,
            clinical=clinical_result.model_dump() if clinical_result else None,
            unified_representation=unified,
            modality_contributions=contributions,
            retrieval_query=retrieval_query,
            uncertainty_block=uncertainty_block,
            model=models["fusion"],
            models=models,
            limitations=self._limitations(),
            safety=SafetyNotice(
                disclaimer=settings.SAFETY_DISCLAIMER,
                human_review_required=True,
                human_review_notice=settings.HUMAN_REVIEW_NOTICE,
                not_autonomous_diagnosis=True,
            ),
            provenance=provenance,
            stages=timer.stages,
            latency_ms=timer.total_ms,
            request_id=rid,
            warnings=warnings,
        )

    # ------------------------------------------------------------- synthesis
    @staticmethod
    def _synthesize(
        *,
        summary: str,
        candidates: Sequence[CandidateInterpretation],
        observed: Sequence[ObservedEvidence],
        simulated: bool,
    ) -> Tuple[str, str]:
        """Build the headline finding and its rationale, honestly."""
        if candidates:
            first_label = candidates[0].label
            if not first_label.lower().startswith("consistent with"):
                primary = f"Consistent with {first_label}"
            else:
                primary = first_label
            if len(candidates) > 1:
                second_label = candidates[1].label
                if second_label.lower().startswith("consistent with "):
                    second_label = second_label[16:]
                primary += f" vs {second_label}"
        elif simulated:
            primary = (
                "Insufficient grounded evidence for a candidate interpretation. "
                "No local reasoning model was available for this request."
            )
        else:
            primary = "Insufficient grounded evidence to propose a candidate interpretation."

        if summary:
            rationale = summary
        else:
            rationale = (
                "No model-generated rationale is available. "
                f"{len(observed)} observed evidence item(s) were collected across the supplied "
                "modalities. Configure a local LLM (OLLAMA_LLM_MODEL) to enable grounded "
                "reasoning."
            )
            if simulated:
                rationale = "DEMO / SIMULATED: " + rationale
        return truncate(primary, 600), truncate(rationale, 4000)

    @staticmethod
    def _recommendations(
        *,
        candidates: Sequence[CandidateInterpretation],
        clinical: Optional[ClinicalAnalysisResponse],
        observed: Sequence[ObservedEvidence],
    ) -> List[str]:
        """Information-seeking next steps only -- never treatment directives."""
